#!/usr/bin/env node
// Adapts the launcher that GraalVM Web Image generates, so the OpenMana worker
// host controls how the engine starts:
//
// - The generated launcher derives the module URL from the executing script
//   (inside a worker that is the worker's own URL) and reads process.argv.
//   Here both come from globalThis.__openmanaEngineConfig instead, which the
//   host sets before loading the launcher: { wasmUrl, args }.
// - The generated launcher only logs a failed start. Here the run promise is
//   exposed as __openmanaEngineConfig.running, so the host can report a failed
//   instantiation (e.g. a browser without Wasm GC) instead of hanging.
//
//   node postprocess-launcher.mjs <generated.js> <out.js>
//
// Fails loudly if the launcher layout is not the expected one (e.g. after a
// GraalVM update), rather than producing a launcher that silently misbehaves.

import fs from "node:fs";

const [input, output] = process.argv.slice(2);
if (!input || !output) {
  console.error("usage: postprocess-launcher.mjs <generated.js> <out.js>");
  process.exit(2);
}

const source = fs.readFileSync(input, "utf8");
const pattern = /const config = new GraalVM\.Config\(\);\s*GraalVM\.run\(load_cmd_args\(\),\s*config\)\.catch\(e => \{ console\.error\(e\); throw e; \}\);/g;
const matches = source.match(pattern) ?? [];
if (matches.length !== 1) {
  throw new Error(`expected exactly one launcher bootstrap in ${input}, found ${matches.length}; GraalVM launcher layout changed`);
}

const bootstrap = `const config = new GraalVM.Config();
// OpenMana (engine/scripts/postprocess-launcher.mjs): the worker host decides
// where the module lives and how the engine starts, and awaits the result.
const openmana = globalThis.__openmanaEngineConfig;
if (!openmana || typeof openmana.wasmUrl !== "string" || openmana.wasmUrl.length === 0) {
    throw new Error("OpenMana engine: set globalThis.__openmanaEngineConfig = { wasmUrl, args } before loading the launcher");
}
config.wasm_path = openmana.wasmUrl;
openmana.running = GraalVM.run(Array.isArray(openmana.args) ? openmana.args : [], config);`;

const header = `/* OpenMana engine launcher: generated by GraalVM Web Image, post-processed by
 * engine/scripts/postprocess-launcher.mjs (only the final bootstrap differs).
 * The Oracle license headers below apply to the generated runtime code. */
`;
fs.writeFileSync(output, header + source.replace(pattern, bootstrap));
console.error(`[openmana-engine] Launcher angepasst: ${output}`);
