#!/usr/bin/env node
// Generates reachability metadata for GraalVM (reflection) covering Forge's
// own classes, so no card or code path depends on a sample game having
// exercised it: Forge creates triggers, replacement effects, keywords and
// ability effects reflectively by class (TriggerType, ReplacementType,
// ApiType/ReflectionUtil, Keyword).
//
//   node gen-reflection-config.mjs <fat.jar> <out-dir>
//
// Every forge.* class gets all declared constructors registered. Network play
// (forge.gamemodes.net) is left out on purpose: registering it would make
// Netty and jupnp (CDDL, see docs/research/LICENSES.md) reachable.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const [jar, outDir] = process.argv.slice(2);
if (!jar || !outDir) {
  console.error("usage: gen-reflection-config.mjs <fat.jar> <out-dir>");
  process.exit(2);
}

const EXCLUDED_PREFIXES = ["forge/gamemodes/net/"];

const entries = execFileSync("jar", ["--list", "--file", jar], { encoding: "utf8", maxBuffer: 1 << 28 })
  .split("\n")
  .map((line) => line.trim())
  .filter((name) => name.startsWith("forge/") && name.endsWith(".class"))
  .filter((name) => !EXCLUDED_PREFIXES.some((prefix) => name.startsWith(prefix)))
  .filter((name) => !name.endsWith("module-info.class") && !name.endsWith("package-info.class"));

const types = [...new Set(entries.map((name) => name.slice(0, -".class".length).replaceAll("/", ".")))].sort();
if (types.length < 1000) {
  throw new Error(`only ${types.length} Forge classes found in ${jar}; wrong JAR?`);
}

const metadata = {
  comment: "Generated by engine/scripts/gen-reflection-config.mjs; do not edit.",
  reflection: types.map((type) => ({ type, allDeclaredConstructors: true })),
};
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "reachability-metadata.json"), JSON.stringify(metadata, null, 1) + "\n");
console.error(`[openmana-engine] Reflection: ${types.length} Forge-Klassen registriert (ohne ${EXCLUDED_PREFIXES.join(", ")})`);
