#!/usr/bin/env node
// Generates reachability metadata for GraalVM (reflection) covering Forge's
// own classes, so no card or code path depends on a sample game having
// exercised it: Forge creates triggers, replacement effects, keywords and
// ability effects reflectively by class (TriggerType, ReplacementType,
// ApiType/ReflectionUtil, Keyword).
//
//   node gen-reflection-config.mjs <fat.jar> <out-dir>
//
// Every forge.* class gets all declared constructors registered. Network play
// (forge.gamemodes.net) is left out on purpose: registering it would make
// Netty and jupnp (CDDL, see docs/research/LICENSES.md) reachable. Interfaces
// are left out too: they have no constructors, and a registered interface
// keeps its method signatures as reflection metadata - IGuiBase and
// IDeviceAdapter declare getUpnpPlatformService() and made jupnp's
// UpnpServiceConfiguration reachable (found by build-wasm.sh's network gate,
// prompt 04).
//
// Every Guava @Subscribe method of those classes is registered too (listed by
// ListSubscribers.java): Forge delivers game events through Guava's EventBus,
// which finds subscribers reflectively. An unregistered subscriber silently
// receives nothing, e.g. the GUI event handler of a human player (prompt 02).
// OpenMana's own subscribers (org.openmana: the engine trace of the
// differential tests, prompt 05) get their methods registered the same way.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const [jar, outDir] = process.argv.slice(2);
if (!jar || !outDir) {
  console.error("usage: gen-reflection-config.mjs <fat.jar> <out-dir>");
  process.exit(2);
}

const EXCLUDED_PREFIXES = ["forge/gamemodes/net/"];

const entries = execFileSync("jar", ["--list", "--file", jar], { encoding: "utf8", maxBuffer: 1 << 28 })
  .split("\n")
  .map((line) => line.trim())
  .filter((name) => name.startsWith("forge/") && name.endsWith(".class"))
  .filter((name) => !EXCLUDED_PREFIXES.some((prefix) => name.startsWith(prefix)))
  .filter((name) => !name.endsWith("module-info.class") && !name.endsWith("package-info.class"));

// `java` is the pinned GraalVM (build-wasm.sh activates the toolchain).
const listSubscribers = path.join(path.dirname(fileURLToPath(import.meta.url)), "ListSubscribers.java");
const interfaces = new Set(
  execFileSync("java", [listSubscribers, "--interfaces", jar, ...EXCLUDED_PREFIXES], { encoding: "utf8", maxBuffer: 1 << 24, stdio: ["ignore", "pipe", "inherit"] })
    .split("\n")
    .filter(Boolean)
    .map((line) => JSON.parse(line).type),
);
if (!interfaces.has("forge.gui.interfaces.IGuiBase")) {
  throw new Error("ListSubscribers --interfaces did not report forge.gui.interfaces.IGuiBase; is the JAR complete?");
}
const types = [...new Set(entries.map((name) => name.slice(0, -".class".length).replaceAll("/", ".")))]
  .filter((type) => !interfaces.has(type))
  .sort();
if (types.length < 1000) {
  throw new Error(`only ${types.length} Forge classes found in ${jar}; wrong JAR?`);
}
const subscribers = execFileSync("java", [listSubscribers, jar, ...EXCLUDED_PREFIXES], {
  encoding: "utf8",
  maxBuffer: 1 << 24,
  stdio: ["ignore", "pipe", "inherit"],
})
  .split("\n")
  .filter(Boolean)
  .map((line) => JSON.parse(line));
if (!subscribers.some((s) => s.type === "forge.game.GameLogFormatter")) {
  throw new Error("ListSubscribers did not find Forge's GameLogFormatter subscriber; is the JAR complete?");
}
const methodsByType = new Map();
for (const s of subscribers) {
  if (!methodsByType.has(s.type)) methodsByType.set(s.type, []);
  methodsByType.get(s.type).push({ name: s.name, parameterTypes: s.parameterTypes });
}
const ours = [...methodsByType.keys()].filter((type) => type.startsWith("org.openmana.")).sort();
const unknown = [...methodsByType.keys()].filter((type) => !types.includes(type) && !ours.includes(type));
if (unknown.length > 0) {
  throw new Error(`subscribers outside the registered classes: ${unknown.join(", ")}`);
}
if (!ours.includes("org.openmana.engine.trace.EngineTrace")) {
  throw new Error("ListSubscribers did not find the engine trace's subscriber (org.openmana.engine.trace.EngineTrace); is the JAR complete?");
}

const metadata = {
  comment: "Generated by engine/scripts/gen-reflection-config.mjs; do not edit.",
  reflection: [
    ...types.map((type) =>
      methodsByType.has(type) ? { type, allDeclaredConstructors: true, methods: methodsByType.get(type) } : { type, allDeclaredConstructors: true },
    ),
    ...ours.map((type) => ({ type, methods: methodsByType.get(type) })),
  ],
};
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "reachability-metadata.json"), JSON.stringify(metadata, null, 1) + "\n");
console.error(
  `[openmana-engine] Reflection: ${types.length} Forge-Klassen registriert (ohne ${EXCLUDED_PREFIXES.join(", ")} und ${interfaces.size} Schnittstellen), ` +
    `davon ${methodsByType.size - ours.length} mit EventBus-Abonnenten (@Subscribe), dazu ${ours.length} OpenMana-Klasse(n); ${subscribers.length} Abonnenten insgesamt`,
);
